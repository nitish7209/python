# Type Conversion
# Implicit Conversion

#  Int -> String
a = 12;
print(type(a))
a = str(a)
print(type(a))

#  String -> Int
a = "12";
print(type(a))
a = int(a)
print(type(a))

#  Float -> Int
a = 12.5;
print(type(a))
a = int(a)
print(type(a))


#  Int -> Float
a = 12;
print(type(a))
a = float(a)
print(type(a))


# in boolean
a = True;
print(type(a))
a = int(a)
print(type(a))

