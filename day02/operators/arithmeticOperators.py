a = 10
b = 15

sum = a + b
print(f"Sum: {sum}") 

sub = b - a
print(f"Subtraction: {sub}")

mul = a * b
print(f"Multiplication: {mul}")

div = a / b
print(f"Division: {div}")

mod = a % b
print(f"Modulus: {mod}")

exp = a ** b
print(f"Exponentiation: {exp}")

floordiv = a // b
print(f"Floor Division: {floordiv}")